package loops;
public class character {
    public static void main(String[] args) {

        char ch = 'e';

        if(ch == 'A' || ch == 'E' || ch == 'I' || ch == 'O' || ch == 'U') {
            System.out.println("It is a vowel.");
        } else {
            System.out.println("It is not a vowel.");
        }
    }
}